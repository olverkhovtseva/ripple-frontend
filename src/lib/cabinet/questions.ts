export function getScenarioPromptItems(audience: Audience): ScenarioPrompt[] {
  return audience === "colleague" ? colleaguePrompts : LOVED_SCENARIO_PROMPTS;
}

/** Вопросы без подсказок (для совместимости). */
export function getScenarioPrompts(audience: Audience): string[] {
  return getScenarioPromptItems(audience).map((p) => p.question);
}

export function fillHeroName(text: string, heroName: string): string {
  const name = heroName.trim() || "героя";
  return text
    .replaceAll("[Имя]", name)
    .replaceAll("[имя]", name)
    .replaceAll("[имя героя]", name)
    .replaceAll("[Имя героя]", name)
    .replaceAll("[Герои]", name);
}

export function buildQuestions(
  audience: Audience,
  selectedIndexes: number[],
  heroName: string,
): ProjectQuestion[] {
  const prompts = getScenarioPromptItems(audience);
  return selectedIndexes
    .filter((i) => i >= 0 && i < prompts.length)
    .sort((a, b) => a - b)
    .map((i) => ({
      id: `q-${audience}-${prompts[i].id}`,
      text: fillHeroName(prompts[i].question, heroName),
      hint: fillHeroName(prompts[i].hint, heroName),
    }));
}

export function daysUntil(deadline: string, now = new Date()): number {
  const [y, m, d] = deadline.split("-").map(Number);
  if (!y || !m || !d) return 0;
  const end = new Date(y, m - 1, d);
  const start = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const diff = Math.ceil((end.getTime() - start.getTime()) / 86400000);
  return diff;
}

/** Простое склонение русских имён по падежам. */
export function russianNameCases(name: string): {
  nom: string;
  gen: string;
  dat: string;
  ins: string;
  pre: string;
} {
  const nom = name.trim() || "герой";
  const lower = nom.toLowerCase();

  // Женские на -а / -я (кроме исключений вроде Никита, Илья)
  const masculineA = new Set(["никита", "илья", "кузьма", "фома", "лука"]);
  if (/[ая]$/i.test(nom) && !masculineA.has(lower)) {
    if (/ия$/i.test(nom)) {
      // Мария → Марии / Марией
      const stem = nom.slice(0, -1);
      return {
        nom,
        gen: stem + "и",
        dat: stem + "и",
        ins: stem + "ей",
        pre: stem + "и",
      };
    }
    if (/ья$/i.test(nom)) {
      // Наталья → Натальи / Наталье / Натальей
      const stem = nom.slice(0, -1);
      return {
        nom,
        gen: stem + "и",
        dat: stem + "е",
        ins: stem + "ей",
        pre: stem + "е",
      };
    }
    if (/а$/i.test(nom)) {
      const stem = nom.slice(0, -1);
      const last = stem.slice(-1).toLowerCase();
      const genEnd = "гкхжшщч".includes(last) ? "и" : "ы";
      const insEnd = "жшщчц".includes(last) ? "ей" : "ой";
      return {
        nom,
        gen: stem + genEnd,
        dat: stem + "е",
        ins: stem + insEnd,
        pre: stem + "е",
      };
    }
    // -я
    const stem = nom.slice(0, -1);
    return {
      nom,
      gen: stem + "и",
      dat: stem + "е",
      ins: stem + "ей",
      pre: stem + "е",
    };
  }

  if (/ий$/i.test(nom)) {
    // Дмитрий → Дмитрия / Дмитрию / Дмитрием / Дмитрии
    const stem = nom.slice(0, -2);
    return {
      nom,
      gen: stem + "ия",
      dat: stem + "ию",
      ins: stem + "ием",
      pre: stem + "ии",
    };
  }
  if (/ей$/i.test(nom)) {
    // Алексей → Алексея / Алексею / Алексеем / Алексее
    const stem = nom.slice(0, -1);
    return {
      nom,
      gen: stem + "я",
      dat: stem + "ю",
      ins: stem + "ем",
      pre: stem + "е",
    };
  }
  if (/й$/i.test(nom)) {
    const stem = nom.slice(0, -1);
    return {
      nom,
      gen: stem + "я",
      dat: stem + "ю",
      ins: stem + "ем",
      pre: stem + "е",
    };
  }
  if (/ь$/i.test(nom)) {
    const stem = nom.slice(0, -1);
    return {
      nom,
      gen: stem + "я",
      dat: stem + "ю",
      ins: stem + "ем",
      pre: stem + "е",
    };
  }

  // Мужские на согласную: Иван → Ивана / Ивану / Иваном / Иване
  return {
    nom,
    gen: nom + "а",
    dat: nom + "у",
    ins: nom + "ом",
    pre: nom + "е",
  };
}

